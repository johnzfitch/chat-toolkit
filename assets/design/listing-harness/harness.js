// Development-only harness: loads the real panel code with stubbed browser
// APIs and arranges one UI state per ?state= value for listing screenshots.
(async () => {
    const params = new URLSearchParams(location.search);
    const state = params.get('state') || 'default';
    const dock = params.get('dock') || 'left';
    if (dock === 'right') document.body.classList.add('dock-right');

    const lib = '../../../extension-src/lib/';
    const load = (src) => new Promise((resolve, reject) => {
        const script = document.createElement('script');
        script.src = src;
        script.onload = resolve;
        script.onerror = () => reject(new Error(`Could not load ${src}`));
        document.head.appendChild(script);
    });

    // Keep closed shadow roots reachable to arrange states. The extension
    // itself never exposes them.
    const roots = [];
    const attach = HTMLElement.prototype.attachShadow;
    HTMLElement.prototype.attachShadow = function (options) {
        const root = attach.call(this, options);
        roots.push(root);
        return root;
    };

    window.__chatToolkit = { PLATFORM: 'demo', safeStringify: (value) => JSON.stringify(value, null, 2) };
    await load(lib + 'ui-model.js');
    window.__chatToolkit.model.PROVIDERS.demo = { name: 'Example chat', hosts: [] };
    await load(lib + 'ui-panel.js');
    const CT = window.__chatToolkit;

    const prefs = { dock, collapsed: state === 'collapsed', format: state === 'json' ? 'json' : 'md', scope: state === 'json' ? 'user' : 'all' };
    const host = CT.createPanel(async () => ({}), { prefs, onPrefs() {} });
    document.body.appendChild(host);
    await new Promise((resolve) => setTimeout(resolve, 50));
    const panel = CT.panel();
    const shadow = roots[0];

    if (state === 'default' || state === 'json') {
        panel.confirm(state === 'json' ? 'copy' : 'save', 'ok', 'Saved', '4 messages from Example chat.');
    }
    if (state === 'advanced') {
        shadow.querySelector('details').open = true;
        panel.setCommand('run-sniffer', { label: 'Show network report', pressed: true });
        panel.setActivity(['Network inspector recording']);
    }
    if (state === 'menu') {
        shadow.querySelector('[aria-label="Panel menu"]').click();
    }
    if (state === 'collapsed') {
        CT.notify('Copied Markdown', '4 messages from Example chat.', 'ok');
    }
    if (state === 'report') {
        CT.showReport({ report: {
            title: 'Example chat API and page comparison',
            summary: 'Compared 6 normalized API blocks against 6 visible page blocks.',
            rows: [{ source: 'api_only', role: 'assistant', kind: 'thinking', preview: 'Reasoning supplied by the provider but not shown on the page' }],
            data: { api_block_count: 6, dom_block_count: 6, dom_only: [], api_only: [{ kind: 'thinking' }] }
        } });
    }
    if (state === 'popup') {
        // popup-preview.html is generated by scripts/capture-listing-screenshots.py.
        const frame = document.getElementById('popup');
        frame.style.display = 'block';
        frame.style.height = '520px';
        await new Promise((resolve) => { frame.onload = resolve; frame.src = 'popup-preview.html'; });
        await new Promise((resolve) => setTimeout(resolve, 400));
        host.remove();
    }
    document.documentElement.dataset.ready = '1';
})().catch((error) => {
    document.documentElement.dataset.ready = 'error:' + error.message;
});
